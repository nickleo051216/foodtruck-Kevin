-- =====================================================================
-- 餐車市集排班系統｜試用版資料庫 第 5 部分：排程
--
-- 白話說明：
--   每分鐘檢查一次「遞補待確認」是否超過 30 分鐘。
--   超過就讓給下一位，並放一則推播進待發清單。
--   這是驗收標準「取消後 1 分鐘內遞補」的關鍵。
--
--   需要 Supabase 的 pg_cron 擴充功能（免費方案可用）。
--   本機測試環境沒有 pg_cron，所以測試腳本會跳過這個檔案。
-- =====================================================================

create extension if not exists pg_cron;

select cron.schedule(
  'foodtruck-expire-offers',      -- 同名排程重複執行只會更新，不會重複建立
  '* * * * *',                    -- 每分鐘
  $$select public.expire_offers()$$
);
